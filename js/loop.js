// For loop, using 3 statement
for (i = 0; i < 5; i = i + 1) {
    console.log("Looping")
}

// Initiating an array
let arrayLoop = ['A', 'B', 'C', 'D']

// Show length of an array
console.log(arrayLoop.length)

// Looping an array using for loop
for (j = 0; j < arrayLoop.length; j++) {
    // Pick each index from array
    console.log(arrayLoop[j])
}

// While loop
let k = 0
while (k < 5) {
    k++
    console.log("While Loop")
}

// Do while loop
let l = 5
do {
    l++
    console.log ("Do while loop")
} while (l < 5)