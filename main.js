// Variable in JavaScript

var name = "Dhia"; // Var is used to declare a variable, also string is defined in double quotes ("")

let age = 20; // Let is used to declare a block-scoped variable, also integer is defined without quotes

const country = "Indonesia"; // Const is used to declare a constant variable

let height = 167.5; // Float is defined without quotes and uses a decimal point (.)

let isStudent = true; // Boolean is defined without quotes and can be either true or false

